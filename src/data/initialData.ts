// Helper to generate realistic candles strictly bounded to TradingView anchor (within <= 1.5 points)
export function generateCandles(basePrice: number, timeframe: Timeframe, count: number = 80, decimals: number = 5): Candle[] {
  const rawCandles: Candle[] = [];
  const now = Date.now();
  let intervalMs = 60 * 1000;
  if (timeframe === '1M') intervalMs = 60 * 1000;
  if (timeframe === '5M') intervalMs = 5 * 60 * 1000;
  if (timeframe === '15M') intervalMs = 15 * 60 * 1000;
  if (timeframe === '1H') intervalMs = 60 * 60 * 1000;
  if (timeframe === '4H') intervalMs = 4 * 60 * 60 * 1000;
  if (timeframe === '1D') intervalMs = 24 * 60 * 60 * 1000;
  if (timeframe === '1W') intervalMs = 7 * 24 * 60 * 60 * 1000;

  // Ensure rich multi-wave amplitude scaled to both instrument decimals and price level so no currency ever flattens into a straight line
  const minTick = Math.pow(10, -decimals);
  const maxAllowedDev = Math.max(
    minTick * 45,
    basePrice > 10000
      ? basePrice * 0.0022
      : basePrice > 1000
      ? basePrice * 0.0018
      : basePrice > 50
      ? basePrice * 0.0025
      : basePrice > 5
      ? basePrice * 0.003
      : basePrice * 0.0025
  );

  // Realistic natural wave parameters with guaranteed multi-tick body movement
  const typicalBody = Math.max(minTick * 5, maxAllowedDev * 0.16);
  let trendDirection = 1; // 1 for bull run, -1 for bear run
  let waveLength = Math.floor(Math.random() * 4 + 3); // 3-6 candles per wave

  const deltas: { o: number; h: number; l: number; c: number; v: number }[] = [];
  let price = basePrice;

  // Walk backwards from now so current bar connects at basePrice
  for (let i = 0; i < count; i++) {
    waveLength--;
    if (waveLength <= 0) {
      trendDirection = -trendDirection;
      waveLength = Math.floor(Math.random() * 4 + 3);
    }

    const isBull = trendDirection > 0;
    const bodySize = Math.max(typicalBody * 0.4, typicalBody * (0.6 + Math.random() * 0.5));

    let cOpen = price;
    let cClose = isBull ? cOpen + bodySize : cOpen - bodySize;

    // Keep price firmly within maxAllowedDev bound of basePrice
    if (cClose > basePrice + maxAllowedDev) {
      cClose = basePrice + maxAllowedDev - Math.random() * typicalBody;
      trendDirection = -1;
      waveLength = 4;
    } else if (cClose < basePrice - maxAllowedDev) {
      cClose = basePrice - maxAllowedDev + Math.random() * typicalBody;
      trendDirection = 1;
      waveLength = 4;
    }

    // Natural clean wicks (small, proportional, 10-25% of body like genuine TradingView candles)
    const hasTopWick = Math.random() > 0.35;
    const hasBottomWick = Math.random() > 0.35;
    const topWick = hasTopWick ? Math.random() * bodySize * 0.22 : 0;
    const bottomWick = hasBottomWick ? Math.random() * bodySize * 0.22 : 0;

    const cHigh = Math.min(basePrice + maxAllowedDev, Math.max(cOpen, cClose) + topWick);
    const cLow = Math.max(basePrice - maxAllowedDev, Math.min(cOpen, cClose) - bottomWick);
    const volume = Math.floor(Math.random() * 300 + 120);

    deltas.unshift({ o: cOpen, h: cHigh, l: cLow, c: cClose, v: volume });
    price = cClose;
  }

  // Exact anchor shift to align the final candle close to basePrice
  const lastDelta = deltas[deltas.length - 1];
  const offset = basePrice - lastDelta.c;

  // Clock slot aligned so new candles form right when timeframe period is over
  const currentSlot = Math.floor(now / intervalMs) * intervalMs;

  for (let i = 0; i < deltas.length; i++) {
    const d = deltas[i];
    const time = currentSlot - (deltas.length - 1 - i) * intervalMs;
    const isLast = i === deltas.length - 1;

    const o = Number((d.o + offset).toFixed(decimals));
    const c = Number((isLast ? basePrice : d.c + offset).toFixed(decimals));
    const h = Number((Math.max(o, c, d.h + offset)).toFixed(decimals));
    const l = Number((Math.min(o, c, d.l + offset)).toFixed(decimals));

    rawCandles.push({
      time,
      open: o,
      high: h,
      low: l,
      close: c,
      volume: d.v,
    });
  }

  return rawCandles;
}
